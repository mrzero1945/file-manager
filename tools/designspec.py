def superellipse_path(cx, cy, rx, ry, n=5.0, steps=512):
    """Closed superellipse (squircle) as a cubic-free polyline path.

    Sampled densely and emitted as straight segments: at launcher sizes the
    deviation from the true curve is far below one pixel.
    """
    import math
    pts = []
    for i in range(steps):
        t = 2.0 * math.pi * i / steps
        ct, st = math.cos(t), math.sin(t)
        x = cx + rx * math.copysign(abs(ct) ** (2.0 / n), ct)
        y = cy + ry * math.copysign(abs(st) ** (2.0 / n), st)
        pts.append((x, y))
    d = [f"M{pts[0][0]:.2f},{pts[0][1]:.2f}"]
    for x, y in pts[1:]:
        d.append(f"L{x:.2f},{y:.2f}")
    d.append("Z")
    return "".join(d)


def folder_glyph_path(size):
    """File Manager folder glyph, normalised into a `size` box centred on 0,0."""
    # Designed in a 24-unit grid, then scaled/translated.
    w = size / 24.0
    off_x = -size / 2.0
    off_y = -size / 2.0

    def p(d):
        import re
        out = []
        for tok in re.split(r"([MLHVZmlhvz])|(-?\d*\.?\d+)", d):
            if not tok:
                continue
            if tok in "MLHVZmlhvz":
                out.append(tok)
            else:
                out.append(f"{float(tok) * w:.2f}")
        return " ".join(out)

    return (
        p("M2.4,9.1 C2.4,7.7 3.6,6.5 5,6.5 H9 C9.8,6.5 10.5,6.9 11,7.5 "
          "L12.2,9 H19 C20.4,9 21.6,10.2 21.6,11.6 V17.4 "
          "C21.6,18.8 20.4,20 19,20 H5 C3.6,20 2.4,18.8 2.4,17.4 Z"),
        (off_x, off_y),
    )
